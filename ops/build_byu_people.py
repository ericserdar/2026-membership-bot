"""
Build byu_people.json: the BYU players, coaches and staff AutoMod protects.

Eric (Nov 17 2026): only OUR players and coaches are protected. Opposing
players, opposing coaches, media and everyone else are fair game for
criticism, so the classifier needs to know who is actually BYU.

Sources:
  - Football players + coaches (with nicknames): ~/Claude/CougConnect/rosters/football_2026.json
    (kept current by Tools/scripts/sync_football_roster.py)
  - Basketball players + coaches (with nicknames, numbers, positions): ~/Claude/CougConnect/rosters/basketball_2026_2027.json
    (Nov 23 2026; built from ESPN + byucougars.com). ESPN players and byucougars.com staff cards are merged in as a
    top-up so late adds are still protected.

The bot also refreshes PLAYER names from ESPN once a day at runtime
(automod._maybe_refresh_roster), so new arrivals are picked up between
rebuilds. Coaches/staff and nicknames only change when this is rerun.

Usage:  python3 ops/build_byu_people.py            # dry run: prints counts + diff
        python3 ops/build_byu_people.py --apply    # writes byu_people.json
"""

import argparse
import html
import json
import os
import re
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "byu_people.json")
FOOTBALL = os.path.expanduser("~/Claude/CougConnect/rosters/football_2026.json")
BASKETBALL = os.path.expanduser("~/Claude/CougConnect/rosters/basketball_2026_2027.json")
ESPN_ROSTER = "https://site.api.espn.com/apis/site/v2/sports/{path}/teams/252/roster"
BB_ROSTER_PAGE = "https://byucougars.com/sports/mens-basketball/roster"
# Coaching staff only, not sports medicine / academic / comms rows further down the page.
BB_STAFF_TITLES = re.compile(r"head coach|assistant coach|associate head|chief of staff|director of (recruiting|basketball operations)", re.I)

# Nicknames members actually use that the source files don't carry.
EXTRA_NICKNAMES = {
    "Aaron Roderick": ["ARod", "A-Rod"],
    "Kalani Sitake": ["Coach Kalani"],
    "Kevin Young": ["KY", "Coach Young"],
}


def _get(url: str) -> str:
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    return urllib.request.urlopen(req, timeout=30).read().decode("utf-8", "ignore")


def espn_players(sport_path: str) -> list[str]:
    data = json.loads(_get(ESPN_ROSTER.format(path=sport_path)))
    athletes = data.get("athletes", [])
    if athletes and "items" in athletes[0]:
        athletes = [a for group in athletes for a in group["items"]]
    return sorted({a["fullName"] for a in athletes if a.get("fullName")})


def bb_staff() -> list[dict]:
    page = _get(BB_ROSTER_PAGE)
    section = page[page.find("Coaching Staff"):]
    names = re.findall(r'roster-card-item__title"[^>]*>.*?<a[^>]*>(.*?)</a>', section, re.S)
    titles = re.findall(r'roster-card-item__position[^"]*"[^>]*>(.*?)</', section, re.S)
    clean = lambda s: html.unescape(re.sub(r"<[^>]+>", "", s)).strip()
    return [{"name": clean(n), "title": clean(t)} for n, t in zip(names, titles) if BB_STAFF_TITLES.search(clean(t))]


def entry(name: str, title: str = "", nicknames=None) -> dict:
    nick = list(dict.fromkeys((nicknames or []) + EXTRA_NICKNAMES.get(name, [])))
    e = {"name": name}
    if title:
        e["title"] = title
    if nick:
        e["nicknames"] = nick
    return e


def bb_people() -> dict:
    bb = json.load(open(BASKETBALL))
    def pos(p):
        return " ".join(x for x in (f"#{p['number']}" if p.get("number") not in (None, "") else "", p.get("position") or "") if x)
    players = [entry(p["name"], pos(p), p.get("nicknames")) for p in bb["players"] if p.get("active", True)]
    coaches = [entry(c["name"], c.get("title", ""), c.get("nicknames")) for c in bb["coaches"] if c.get("active", True)]
    known_p, known_c = {p["name"] for p in players}, {c["name"] for c in coaches}
    try:
        players += [entry(n) for n in espn_players("basketball/mens-college-basketball") if n not in known_p]
        coaches += [entry(s["name"], s["title"]) for s in bb_staff() if s["name"] not in known_c]
    except Exception as e:   # the file alone is enough; the web top-up is best-effort
        print(f"basketball web top-up skipped: {e!r}")
    return {"coaches": coaches, "players": players}


def build() -> dict:
    fb = json.load(open(FOOTBALL))
    fb_players = [entry(p["name"], p.get("position", ""), p.get("nicknames")) for p in fb["players"] if p.get("active", True)]
    known = {p["name"] for p in fb_players}
    # ESPN may list someone the local file doesn't yet (walk-ons, late adds).
    fb_players += [entry(n) for n in espn_players("football/college-football") if n not in known]
    return {
        "_note": "Generated by ops/build_byu_people.py. AutoMod protects ONLY these BYU people (plus community members).",
        "football": {
            "coaches": [entry(c["name"], c.get("title", ""), c.get("nicknames")) for c in fb["coaches"] if c.get("active", True)],
            "players": fb_players,
        },
        "basketball": bb_people(),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    args = ap.parse_args()
    new = build()
    old = json.load(open(OUT)) if os.path.exists(OUT) else {}
    for sport in ("football", "basketball"):
        for kind in ("coaches", "players"):
            n = {e["name"] for e in new[sport][kind]}
            o = {e["name"] for e in old.get(sport, {}).get(kind, [])}
            print(f"{sport} {kind}: {len(n)}" + (f"  +{sorted(n - o)}" if o and n - o else "")
                  + (f"  -{sorted(o - n)}" if o - n else ""))
    if not new["basketball"]["coaches"] or not new["football"]["coaches"]:
        raise SystemExit("A sport came back with no coaches; refusing to write.")
    if args.apply:
        with open(OUT, "w") as f:
            json.dump(new, f, indent=1, ensure_ascii=False)
        print(f"wrote {os.path.normpath(OUT)}")
    else:
        print("dry run; --apply to write")


if __name__ == "__main__":
    main()
